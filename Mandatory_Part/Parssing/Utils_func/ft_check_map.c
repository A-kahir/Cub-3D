#include "../parsing.h"

int ft_check_map(char *line)
{
	if ((line[0] == '\n' || (line[0] == 32 || (line[0] >= 9 && line[0] <= 13))))
		return (-1);
	if (line && ft_if_valid_map(line, 0) == -1)
		return (-2);
	return (0);
}
