#include "../cub_mand.h"

int	ft_lenght_j(t_source *src)
{
	t_source	*curr;
	int			i;
	int			j;

	i = 0;
	j = -1;
	curr = src;
	while (curr->map[i])
	{
		j++;
		i++;
	}
	return (j);
}
